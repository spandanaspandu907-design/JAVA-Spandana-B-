public class DefaultValue {
    int a;
    double b;
    boolean c;
    char d;

    public static void main(String[] args) {
        DefaultValue obj = new DefaultValue();

        System.out.println("Integer: " + obj.a);
        System.out.println("Double: " + obj.b);
        System.out.println("Boolean: " + obj.c);
        System.out.println("Character: " + obj.d);
    }
}